"""Write mobile/shared/web/strings.js from the desktop app's interface strings.

Run after changing src/ficbook_dl/i18n.py:  python3 mobile/tools/export_strings.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from ficbook_dl import __version__  # noqa: E402
from ficbook_dl.i18n import TEXT  # noqa: E402

OUT = ROOT / "mobile" / "shared" / "web" / "strings.js"


def main() -> None:
    body = json.dumps(TEXT, ensure_ascii=False, indent=1)
    OUT.write_text(
        "// Generated by mobile/tools/export_strings.py from src/ficbook_dl/i18n.py. Do not edit.\n"
        f"window.FICBOOK_VERSION = {json.dumps(__version__)};\n"
        f"window.FICBOOK_TEXT = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
